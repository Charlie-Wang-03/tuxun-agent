// Supports exact message keys and tagged templates. Values are interpolated once,
// so recorded content containing braces is preserved verbatim.
export function translate(language, value, ...values) {
  const key = Array.isArray(value) ? value.map((part,i)=>part+(i<values.length?`{${i}}`:'')).join('') : String(value ?? '');
  const template = language === 'en' ? english[key] ?? key : key;
  return template.replace(/\{(\d+)\}/g,(whole,index)=>Number(index)<values.length?String(values[Number(index)]):whole);
}
export const message = (value,...values)=>translate('zh',value,...values);

// Capture only the original static DOM. Dynamic content is rendered explicitly
// by the client and is not scanned, rewritten or sent to a translation service.
export function bindStaticMessages(document, t) {
  const nodes=[], attributes=[];
  const walker=document.createTreeWalker(document.documentElement,4);
  while(walker.nextNode()) {
    const node=walker.currentNode;
    if(!node.parentElement.closest('script,style,svg') && node.data.trim())nodes.push({node,source:node.data});
  }
  for(const node of document.querySelectorAll('[aria-label],[alt],[title]')) {
    for(const name of ['aria-label','alt','title'])if(node.hasAttribute(name))attributes.push({node,name,source:node.getAttribute(name)});
  }
  return ()=>{
    for(const {node,source} of nodes)if(node.isConnected) {
      const key=source.trim();node.data=source.replace(key,t(key));
    }
    for(const {node,name,source} of attributes)if(node.isConnected)node.setAttribute(name,t(source));
  };
}
